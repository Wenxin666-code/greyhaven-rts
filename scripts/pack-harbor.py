"""Pack the harbor's native isometric frames and render a review sheet."""
import io
import json
import struct
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "art/source/harbor-v01"
FRAMES = ART / "frames"


def frame_path(name, number, paint=False):
    return FRAMES / name / f"{number}{'-paint' if paint else ''}.png"


def rgba(name, number, paint=False):
    with Image.open(frame_path(name, number, paint)) as image:
        return image.convert("RGBA")


def union(first, second):
    if first is None:
        return second
    return (min(first[0], second[0]), min(first[1], second[1]),
            max(first[2], second[2]), max(first[3], second[3]))


def coat_alpha(paint):
    red, green, blue, alpha = paint.split()
    return ImageChops.multiply(ImageChops.lighter(ImageChops.lighter(red, green), blue), alpha)


def image_bytes(name, number, paint, crop):
    data = io.BytesIO()
    rgba(name, number, paint).crop(crop).save(data, format="PNG", compress_level=6)
    return data.getvalue()


def pack_frames(specs):
    density = specs["landing"]["density"]
    rows, entries = [], []
    for name, spec in specs.items():
        bounds = None
        expected_size = spec["width"], spec["height"]
        if spec["density"] != density:
            raise ValueError(f"{name} has a different camera scale")
        coverage = []
        for number in range(spec["frames"]):
            body = rgba(name, number)
            paint = rgba(name, number, True)
            if body.size != expected_size or paint.size != body.size:
                raise ValueError(f"{name}/{number} changed frame dimensions")
            alpha = body.getchannel("A")
            box = alpha.getbbox()
            if not box or min(box[0], box[1], expected_size[0]-box[2], expected_size[1]-box[3]) < 2:
                raise ValueError(f"{name}/{number} is empty or clipped: {box}")
            coat = coat_alpha(paint)
            outside = ImageChops.multiply(coat, alpha.point(lambda a: 255 if a == 0 else 0))
            if outside.point(lambda a: 255 if a > 12 else 0).getbbox():
                raise ValueError(f"{name}/{number} paint extends beyond its silhouette")
            coverage.append(sum(coat.histogram()[36:]) / max(1, sum(alpha.histogram()[36:])))
            bounds = union(bounds, box)
        if name not in ("cargo", "bollard") and max(coverage) < .08:
            raise ValueError(f"{name} has insufficient faction paint")
        l, t, r, b = bounds
        crop = l-1, t-1, r+1, b+1
        x, y = crop[0] - spec["anchorX"], crop[1] - spec["anchorY"]
        w, h = crop[2] - crop[0], crop[3] - crop[1]
        rows.append(f'        internal static readonly HarborSprite {name.title()} = '
                    f'new HarborSprite("{name}", {spec["frames"]}, new Rectangle({x}, {y}, {w}, {h}));')
        for number in range(spec["frames"]):
            for is_paint in (False, True):
                key = f"harbor/{name}/{number}" + ("-paint" if is_paint else "")
                entries.append((key.encode("utf-8"), image_bytes(name, number, is_paint, crop)))
        print(f"{name:8} {w:3} × {h:3}  {spec['frames']:2} frames  paint {max(coverage):.1%}")
    output = ART / "packed/harbor-v01.pak"
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("wb") as stream:
        stream.write(b"GHBLD008" + struct.pack("<i", len(entries)))
        offset = 0
        for key, data in entries:
            stream.write(struct.pack("<H", len(key)) + key + struct.pack("<qi", offset, len(data)))
            offset += len(data)
        for _, data in entries:
            stream.write(data)
    metadata = "// Generated by scripts/pack-harbor.py.\nusing System.Drawing;\n\nnamespace Greyhaven {\n"
    metadata += "    internal static partial class HarborSprites {\n"
    metadata += f"        internal const float Density = {density:.6f}f;\n"
    metadata += "\n".join(rows) + "\n    }\n}\n"
    (ROOT / "src/HarborArtMetadata.cs").write_text(metadata, encoding="utf-8")
    print(f"Harbor pack {len(entries)} layers, {output.stat().st_size:,} bytes")


def apply_coat(base, paint, color):
    alpha, mask = base.getchannel("A"), paint.getchannel("A")
    tinted = []
    for channel, rgb in zip("RGB", color):
        neutral = ImageChops.multiply(base.getchannel(channel), alpha)
        coating = ImageChops.multiply(paint.getchannel(channel), mask)
        tinted.append(ImageChops.subtract(neutral, coating.point(lambda v: round(v*(255-rgb)/255))))
    return Image.merge("RGBa", (*tinted, alpha)).convert("RGBA")


def review_sheet(specs):
    sheet = Image.new("RGB", (1680, 1010), "#122124")
    draw = ImageDraw.Draw(sheet)
    fonts = Path("C:/Windows/Fonts")
    regular = fonts / "msyh.ttc"
    bold = fonts / "msyhbd.ttc"
    font = lambda size, heavy=False: ImageFont.truetype(str(bold if heavy else regular), size)
    draw.rectangle((36, 31, 40, 87), fill="#d7ad63")
    draw.text((58, 29), "旧港船只与港区设施", font=font(35, True), fill="#f3eee0")
    draw.text((60, 76), "断线前沿  /  第一章", font=font(15), fill="#b4c2bc")

    def card(rectangle, name, number, label, subtitle, color, max_scale):
        x, y, w, h = rectangle
        draw.polygon([(x+10,y),(x+w,y),(x+w,y+h-10),(x+w-10,y+h),(x,y+h),(x,y+10)],
                     fill="#223438", outline="#62736b")
        draw.line((x+18,y+h-62,x+w-18,y+h-62), fill="#495f5d")
        draw.text((x+20,y+h-53), label, font=font(21,True), fill="#edeade")
        draw.text((x+20,y+h-24), subtitle, font=font(13), fill="#b3c5bb")
        sprite = apply_coat(rgba(name,number), rgba(name,number,True), color)
        sprite = sprite.crop(sprite.getbbox())
        k = min((w-58)/sprite.width,(h-81)/sprite.height,max_scale)
        sprite = sprite.resize((round(sprite.width*k),round(sprite.height*k)),Image.Resampling.LANCZOS)
        position=(x+(w-sprite.width)//2,y+(h-63-sprite.height)//2)
        sheet.paste(sprite,position,sprite)

    blue, neutral, gold = (72,145,198), (197,209,201), (182,143,82)
    card((36,120,788,412),"landing",specs["landing"]["frames"]-1,"浅滩登陆艇",
         "开放车辆甲板  ·  铰接前跳板  ·  蓝色涂装示例",blue,1.53)
    card((856,120,788,412),"supply",0,"港区补给船",
         "高位驾驶台  ·  分区货甲板  ·  中性涂装示例",neutral,1.38)
    card((36,555,520,416),"office",1,"港务中心",
         "2 × 2 格地基  ·  调度灯和窗内照明",neutral,2.1)
    card((580,555,520,416),"crane",round((specs["crane"]["frames"]-1)*.4),"码头吊机",
         "桁架塔身  ·  独立回转、吊索与吊具",gold,1.72)
    card((1124,555,520,416),"gate",17,"货运闸",
         "双臂开合  ·  独立警示色和路况灯",neutral,1.68)
    preview = ART / "review/港区素材.png"
    preview.parent.mkdir(parents=True,exist_ok=True)
    sheet.save(preview)


if __name__ == "__main__":
    manifest = json.loads((FRAMES / "manifest.json").read_text(encoding="utf-8"))
    pack_frames(manifest)
    review_sheet(manifest)
