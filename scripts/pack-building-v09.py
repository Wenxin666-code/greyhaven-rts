"""Pack authored PNG layers without atlases or platform imaging dependencies.

Only code-rendered model frames are cropped; accepted concept images are untouched.
The pack index permits lazy decode of one small animation frame at a time.
"""
from pathlib import Path
from PIL import Image, ImageChops
import argparse, hashlib, io, json, struct

KEYS = ['hq','barracks','factory','power','radar','satellite','post','refinery','residence','shop','municipal']
parser=argparse.ArgumentParser()
parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
args=parser.parse_args();root=args.root;source=root/'art/source/buildings-v09';entries={};records={}

def rgba(path):return Image.open(path).convert('RGBA')
def png(im):
    b=io.BytesIO();im.save(b,format='PNG',optimize=True);return b.getvalue()
def pair(name,base,paint):
    assert base.size==paint.size,name
    entries[name]=png(base);entries[name+'-paint']=png(paint)
def union_bounds(images):
    bounds=[im.getchannel('A').getbbox() for im in images];bounds=[b for b in bounds if b]
    if not bounds:return (0,0,1,1)
    return max(0,min(b[0] for b in bounds)-2),max(0,min(b[1] for b in bounds)-2),min(320,max(b[2] for b in bounds)+2),min(320,max(b[3] for b in bounds)+2)

fingerprints=set();material_hash=hashlib.sha256(b''.join((source/'materials'/name).read_bytes() for name in ['coated-armor.png','cast-concrete.png'])).hexdigest()
for key in KEYS:
    folder=source/'frames'/key;audit=json.loads((folder/'audit.json').read_text(encoding='utf-8'))
    if audit.get('materialFingerprint')!=material_hash:raise ValueError('Material changed since export '+key)
    fingerprints.add(audit['fingerprint']);meta={'stats':audit['stats'],'complete':audit['complete'],'points':audit['points']}
    complete,paint=rgba(folder/'base.png'),rgba(folder/'paint.png');wreck=rgba(folder/'wreck.png')
    sheet=Image.new('RGBA',(320,960));mask=Image.new('RGBA',(320,960))
    for y in [0,320]:sheet.paste(complete,(0,y));mask.paste(paint,(0,y))
    sheet.paste(wreck,(0,640));pair('iso-'+key,sheet,mask)
    pair('b08/'+key+'/background',rgba(folder/'idle-background.png'),rgba(folder/'idle-background-paint.png'))
    for kind in ['build','collapse','idle']+(['door'] if key=='factory' else [])+(['deploy'] if key=='hq' else []):
        count=16 if kind=='door' else 96 if kind in ['idle','deploy'] else 48
        if len(audit['frames'][kind])!=count:raise ValueError(key+'/'+kind+' incomplete')
        bases=[rgba(folder/kind/(str(i)+'.png')) for i in range(count)]
        paints=[rgba(folder/kind/(str(i)+'-paint.png')) for i in range(count)]
        if kind in ['build','collapse']:
            target=complete if kind=='build' else wreck
            diff=ImageChops.difference(bases[-1],target)
            if max(high for low,high in diff.getextrema())>1:raise ValueError(kind+' endpoint '+key)
            # GPU transforms can differ by one 8-bit quantization value. Share
            # the proven endpoint pixels so switching states is bit-exact.
            bases[-1]=target
            paints[-1]=paint if kind=='build' else rgba(folder/'wreck-paint.png')
        crop=union_bounds(bases+paints) if kind in ['idle','door'] else (0,0,320,320)
        meta[kind+'Crop']=list(crop)
        for i,(b,p) in enumerate(zip(bases,paints)):pair(f'b08/{key}/{kind}/{i}',b.crop(crop),p.crop(crop))
    records[key]=meta
    print(key,meta['idleCrop'],flush=True)
if len(fingerprints)!=1:raise ValueError('Mismatched source generations; finish export before packing')

dest=source/'packed';dest.mkdir(exist_ok=True)
# Relative offsets are independent of index length and checked on every read.
index=io.BytesIO();offset=0
for name,data in entries.items():
    encoded=name.encode('utf-8');index.write(struct.pack('<H',len(encoded)));index.write(encoded);index.write(struct.pack('<qi',offset,len(data)));offset+=len(data)
with (dest/'buildings-v09.pak').open('wb') as f:
    f.write(b'GHBLD008');f.write(struct.pack('<i',len(entries)));f.write(index.getvalue())
    for data in entries.values():f.write(data)
manifest={'version':9,'frameSize':320,'buildFrames':48,'collapseFrames':48,'idleFrames':96,'idleFps':24,'deployFrames':96,'doorFrames':16,'bytes':offset,'sourceFingerprint':next(iter(fingerprints)),'materialFingerprint':material_hash,'buildings':records}
(dest/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')

lines=['// Generated by scripts/pack-building-v08.py. Source geometry and crop metadata are authoritative.','using System.Drawing;','using System.Collections.Generic;','namespace Greyhaven {','internal sealed class BuildingV08Spec {',' internal Rectangle Idle,Door; internal PointF Muzzle; internal Dictionary<string,PointF[]> Sockets=new Dictionary<string,PointF[]>(); internal int Width,Depth;',' internal BuildingV08Spec(int w,int d,Rectangle idle,Rectangle door,PointF muzzle){Width=w;Depth=d;Idle=idle;Door=door;Muzzle=muzzle;}','}','internal static partial class BuildingV08 {',' internal static readonly Dictionary<string,BuildingV08Spec> Specs=new Dictionary<string,BuildingV08Spec>{']
def rectangle(b):return 'new Rectangle(%d,%d,%d,%d)'%(b[0],b[1],b[2]-b[0],b[3]-b[1])
for key,r in records.items():
    p=r['points'].get('muzzle') or [0,0];w,d=r['stats']['foundation']
    socket_entries=','.join('{"%s",new PointF[]{%s}}'%(name,','.join('new PointF(%.6ff,%.6ff)'%tuple(v) for v in values)) for name,values in r['points'].get('sockets',{}).items())
    lines.append('  {"%s",SocketSpec(new BuildingV08Spec(%d,%d,%s,%s,new PointF(%.6ff,%.6ff)),new Dictionary<string,PointF[]>{%s})},'%(key,w,d,rectangle(r['idleCrop']),rectangle(r.get('doorCrop',[0,0,1,1])),p[0],p[1],socket_entries))
lines+=[' };',' static BuildingV08Spec SocketSpec(BuildingV08Spec spec,Dictionary<string,PointF[]> sockets){spec.Sockets=sockets;return spec;}','}','}']
(root/'src/BuildingV08Metadata.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8-sig')
print('Packed',len(entries),'images;',round(offset/1048576,2),'MiB')
