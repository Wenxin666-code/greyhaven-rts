"""Pack generated relay frames into the existing bounded, indexed native format."""
from pathlib import Path
import io,json,struct
from PIL import Image

root=Path(__file__).resolve().parents[1]
source=root/'art/source/relay-v01'
audit=json.loads((source/'audit.json').read_text(encoding='utf-8'))
bounds=[f['bounds'] for f in audit['idle'] if f['ink']]
crop=(min(b[0] for b in bounds),min(b[1] for b in bounds),max(b[2] for b in bounds),max(b[3] for b in bounds))
entries=[]
def add(name,file,box=None):
 with Image.open(file) as im:
  if box:im=im.crop(box)
  output=io.BytesIO();im.save(output,format='PNG');entries.append((name,output.getvalue()))
for suffix in ['', '-paint']:
 add('iso-relay'+suffix,source/'frames'/('paint.png' if suffix else 'base.png'))
 add('b08/relay/background'+suffix,source/'frames'/('background'+suffix+'.png'))
 for n in range(96):add('b08/relay/idle/'+str(n)+suffix,source/'frames/idle'/(str(n)+suffix+'.png'),crop)
 for level in range(1,4):
  for kind in ['', '-background']:
   name='damage-'+str(level)+kind+suffix
   add('b08/relay/'+name,source/'frames'/(name+'.png'))
out=source/'packed/relay-v01.pak';out.parent.mkdir(parents=True,exist_ok=True)
with out.open('wb') as f:
 f.write(b'GHBLD008'+struct.pack('<i',len(entries)));offset=0
 for name,data in entries:
  encoded=name.encode();f.write(struct.pack('<H',len(encoded))+encoded+struct.pack('<qi',offset,len(data)));offset+=len(data)
 for name,data in entries:f.write(data)
sockets=','.join('{"%s",new PointF[]{%s}}'%(name,','.join('new PointF(%.6ff,%.6ff)'%tuple(p) for p in points)) for name,points in audit['points']['sockets'].items())
(root/'src/RelayArtMetadata.cs').write_text('''// Generated by scripts/pack-relay.py; canonical camera and independent faction mask.
using System.Drawing;
using System.Collections.Generic;
namespace Greyhaven {internal static partial class BuildingV08 {
 static BuildingV08(){Specs.Add("relay",RelaySpec());Specs.Add("bunker",new BuildingV08Spec(2,2,new Rectangle(0,0,320,320),new Rectangle(0,0,1,1),PointF.Empty));}
 internal static BuildingV08Spec RelaySpec(){return SocketSpec(new BuildingV08Spec(3,3,new Rectangle(%d,%d,%d,%d),new Rectangle(0,0,1,1),PointF.Empty),new Dictionary<string,PointF[]>{%s});}
}}
'''%(crop[0],crop[1],crop[2]-crop[0],crop[3]-crop[1],sockets),encoding='utf-8-sig')
print('Relay pack: %d PNG entries, %d bytes, idle crop %s, faction coverage %.1f%%'%(len(entries),out.stat().st_size,crop,audit['complete']['paintFraction']*100))
