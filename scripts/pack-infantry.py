from pathlib import Path
from PIL import Image
import struct,io,json
root=Path(__file__).resolve().parents[1];source=root/'art/source/infantry-v12';entries={}
def add(key,file):
    entries[key]=file.read_bytes()
for key in ['squad','sniper','at-mobile']:
    for suffix,layer in [('-base','base'),('-paint','paint')]:add(key+suffix,source/'frames'/f'{key}-{layer}.png')
    for v in range(8):
        for i in range(12):
            for suffix in ['','-paint']:add(f'gait/{key}/{v}/{i}{suffix}',source/'frames/gait'/key/str(v)/f'{i}{suffix}.png')
for key in ['squad','at']:
    for v in range(8):
        for i in range(33):
            for suffix in ['','-paint']:add(f'stance/{key}/{v}/{i}{suffix}',source/'frames/stance'/key/str(v)/f'{i}{suffix}.png')
for suffix in ['','-paint']:
    add('iso-bunker'+suffix,source/'frames/bunker'/('paint.png' if suffix else 'base.png'))
    add('b08/bunker/background'+suffix,source/'frames/bunker'/f'background{suffix}.png')
    for action,n in [('idle',96),('build',72)]:
        for i in range(n):add(f'b08/bunker/{action}/{i}{suffix}',source/'frames/bunker'/action/f'{i}{suffix}.png')
    for level in range(1,4):
        for bg in ['','-background']:add(f'b08/bunker/damage-{level}{bg}{suffix}',source/'frames/bunker'/f'damage-{level}{bg}{suffix}.png')
for file in (source/'frames/combat').rglob('*.png'):
    add('combat/'+file.relative_to(source/'frames/combat').as_posix()[:-4],file)
for v in range(8):
    for i in range(12):
        for suffix in ['', '-paint']:add(f'gait/squad/{v}/{i}{suffix}',source/'frames/gait/squad'/str(v)/f'{i}{suffix}.png')
# Crop every dynamic infantry view to its full animation union. The runtime
# maps these bounds back into the same 384-pixel canonical camera.
metadata={}
for group,keys,count in [('gait',['squad','sniper','at-mobile'],12),('combat',['squad','sniper','at','squad-deployed','at-deployed'],17)]:
    for key in keys:
        rects=[]
        for view in range(8):
            files=[source/'frames'/group/key/str(view)/f'{i}{suffix}.png' for i in range(count) for suffix in ['', '-paint']]
            bounds=[]
            for file in files:
                with Image.open(file) as im:
                    box=im.getchannel('A').getbbox()
                    if box:bounds.append(box)
            crop=(max(0,min(b[0] for b in bounds)-2),max(0,min(b[1] for b in bounds)-2),min(384,max(b[2] for b in bounds)+2),min(384,max(b[3] for b in bounds)+2))
            rects.append((crop[0],crop[1],crop[2]-crop[0],crop[3]-crop[1]))
            for file in files:
                with Image.open(file) as im:
                    data=io.BytesIO();im.crop(crop).save(data,format='PNG');entries[group+'/'+key+'/'+str(view)+'/'+file.stem]=data.getvalue()
        metadata[group+'/'+key]=rects
lines=['// Generated by pack-infantry.py; canonical 384px camera.','using System.Drawing;','using System.Collections.Generic;','namespace Greyhaven {internal static class InfantryV12 {','internal static readonly Dictionary<string,Rectangle[]> Crops=new Dictionary<string,Rectangle[]>{']
for key,rects in metadata.items():lines.append('{"'+key+'",new Rectangle[]{'+','.join('new Rectangle(%d,%d,%d,%d)'%r for r in rects)+'}},')
lines+=['};}}'];(root/'src/InfantryV12Metadata.cs').write_text('\n'.join(lines),encoding='utf-8-sig')
out=source/'packed/infantry-v12.pak'  ;out.parent.mkdir(exist_ok=True)
with out.open('wb') as f:
    f.write(b'GHBLD008'+struct.pack('<i',len(entries)));offset=0
    for key,data in entries.items():
        name=key.encode();f.write(struct.pack('<H',len(name))+name+struct.pack('<qi',offset,len(data)));offset+=len(data)
    for data in entries.values():f.write(data)
print(f'Infantry pack: {len(entries)} entries; {out.stat().st_size/1048576:.2f} MiB')
